const episodes = [];
const episodeBlocks = text.split(/EPISODE \d+/).filter(b => b.trim().length > 0);

episodeBlocks.forEach((block, index) => {
  const chapterNumber = parseFloat("1." + (index + 1).toString().padStart(2, '0'));
  
  const extract = (regex) => {
    const match = block.match(regex);
    return match ? match[1].trim() : '';
  };

  const extractList = (regex) => {
    const match = block.match(regex);
    if (!match) return [];
    return match[1].split('●').map(s => s.trim()).filter(s => s.length > 0);
  };

  const title = extract(/“([^”]+)”/);
  const grammarFocus = extract(/Grammar Focus:\s*(.+)/);
  const cefrLevel = extract(/CEFR:\s*(.+)/);
  const episodeJob = extract(/Episode job\n+([\s\S]+?)\n+Logline/);
  const logline = extract(/Logline\n+([\s\S]+?)\n+A-Story/);
  const aStory = extract(/A-Story\n+([\s\S]+?)\n+B-Story/);
  const bStory = extract(/B-Story\n+([\s\S]+?)\n+C-Story/);
  const cStory = extract(/C-Story\n+([\s\S]+?)\n+Core language target/);
  const coreLanguageTarget = extractList(/Core language target\n+([\s\S]+?)\n+Story beats/);
  const storyBeats = extractList(/Story beats\n+([\s\S]+?)\n+Emotional movement/);
  const emotionalMovement = extract(/Emotional movement\n+([\s\S]+?)\n+Writer notes/);
  let writerNotes = extractList(/Writer notes\n+([\s\S]+)$/);
  if (writerNotes.length === 0) {
    writerNotes = extractList(/Writer notes\n+([\s\S]+?)\n+EPISODE/);
  }

  episodes.push({
    chapterNumber,
    title,
    cefrLevel,
    grammarFocus,
    episodeJob,
    logline,
    aStory,
    bStory,
    cStory,
    coreLanguageTarget,
    storyBeats,
    emotionalMovement,
    writerNotes
  });
});

fs.writeFileSync('/app/applet/src/data/episodeOutlines.ts', "export const initialEpisodeOutlines = " + JSON.stringify(episodes, null, 2) + ";");
